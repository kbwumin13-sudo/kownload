#!/usr/bin/env python3
"""Generate checked-in language/build constants from config/identity.json."""
import argparse
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]

def outputs():
    c = json.loads((ROOT / 'config/identity.json').read_text())
    scalar = {k: v for k, v in c.items() if isinstance(v, str)}
    dart = '// Generated by scripts/generate-identity.py.\nclass AppIdentity {\n'
    dart += ''.join(f'  static const {k} = {json.dumps(v)};\n' for k, v in c.items()) + '}\n'
    go = '// Code generated by scripts/generate-identity.py; DO NOT EDIT.\npackage appidentity\n\nconst (\n'
    go += ''.join(f'\t{k[0].upper()+k[1:]} = {json.dumps(v)}\n' for k, v in scalar.items()) + ')\n'
    for k, v in c.items():
        if isinstance(v, list):
            go += '\nvar ' + k[0].upper()+k[1:] + ' = []string{' + ', '.join(json.dumps(x) for x in v) + '}\n'
    swift = '// Generated by scripts/generate-identity.py.\nimport Foundation\nenum AppIdentity {\n'
    swift += ''.join(f'  static let {k} = {json.dumps(v)}\n' for k, v in c.items()) + '}\n'
    xc = '// Generated by scripts/generate-identity.py.\n'
    xc += f'PRODUCT_NAME = {c["productName"]}\nPRODUCT_BUNDLE_IDENTIFIER = {c["bundleId"]}\nKOWNLOAD_SCHEME = {c["scheme"]}\nKOWNLOAD_LEGACY_SCHEME = {c["legacyScheme"]}\n'
    js = '// Generated by scripts/generate-identity.py.\n'
    js += 'export const NATIVE_HOST = ' + json.dumps(c['hostName']) + ';\n'
    return {'ui/flutter/lib/identity/app_identity.dart': dart,
            'browser-media-extension/native-host-identity.js': js,
            'internal/appidentity/identity.go': go,
            'ui/flutter/macos/Runner/AppIdentity.swift': swift,
            'ui/flutter/macos/Runner/Configs/Identity.xcconfig': xc}

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    for name, content in outputs().items():
        file = ROOT / name
        if args.check:
            if not file.exists() or file.read_text() != content:
                raise SystemExit('Identity constants are stale: ' + name)
        else:
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(content)

if __name__ == '__main__':
    main()
